import { Archive, ArchiveRestore, CheckCheck, PenLine, Send, Trash2, Undo2, Upload } from "lucide-react";
import type { ReactNode } from "react";
import { ConfirmAction } from "../ConfirmAction";
import type { AdminFormAction } from "../form-state";

/**
 * Workflow buttons for one content item (§41, §42; CLAUDE.md "Database rules"), each behind a confirmation dialog:
 * Submit for review (DRAFT), Request changes (IN_REVIEW / APPROVED, notes required), Approve (IN_REVIEW; disabled
 * with the reason when four-eyes forbids the author approving their own work; AI drafts require a written review
 * note), Publish (APPROVED), Archive (PUBLISHED live row without a pending edit), Edit published (creates the draft
 * copy), Discard draft copy, Restore to draft (ARCHIVED live row → DRAFT at a new revision). Only transitions that are legal from `status` AND allowed by the viewer's capabilities
 * are shown; every Server Action re-checks permission and calls the shared publish helper. Server component.
 */

export interface WorkflowBarActions {
  submit?: AdminFormAction<unknown>;
  requestChanges?: AdminFormAction<unknown>;
  approve?: AdminFormAction<unknown>;
  publish?: AdminFormAction<unknown>;
  archive?: AdminFormAction<unknown>;
  /** ARCHIVED → DRAFT ("Restore to draft"; shown with the archive capability). */
  reopen?: AdminFormAction<unknown>;
  startEdit?: AdminFormAction<unknown>;
  discard?: AdminFormAction<unknown>;
}

export interface WorkflowBarProps {
  entityType: string;
  id: string;
  status: string;
  /** Set for a draft copy of published content. */
  draftOfId: string | null;
  /** The live row's pending draft copy (blocks archiving; "edit" opens it). */
  pendingDraftId?: string | null;
  aiGenerated: boolean;
  isOwnWork: boolean;
  fourEyes: boolean;
  capabilities: { canDraft: boolean; canReview: boolean; canPublish: boolean; canArchive: boolean };
  actions: WorkflowBarActions;
  /** e.g. "this lesson". */
  itemLabel: string;
  /** Blocking problems (submit stays available: the server lists them as field errors). */
  issueCount?: number;
  className?: string;
}

function capitalise(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

export function ContentWorkflowBar({
  entityType,
  id,
  status,
  draftOfId,
  pendingDraftId = null,
  aiGenerated,
  isOwnWork,
  fourEyes,
  capabilities,
  actions,
  itemLabel,
  issueCount = 0,
  className,
}: WorkflowBarProps) {
  const fields = { entityType, id };
  const approveBlocked = fourEyes && isOwnWork;
  const buttons: ReactNode[] = [];

  if (status === "DRAFT" && capabilities.canDraft && actions.submit) {
    buttons.push(
      <ConfirmAction
        key="submit"
        action={actions.submit}
        fields={fields}
        triggerLabel="Submit for review"
        triggerVariant="primary"
        triggerIcon={<Send aria-hidden="true" />}
        title="Submit for review?"
        description={`A reviewer will check ${itemLabel} before it can be published. Editing is locked while it is in review.`}
        confirmLabel="Submit for review"
        successMessage="Submitted for review."
      >
        {issueCount > 0 && (
          <p className="text-warning-text">
            {issueCount} problem{issueCount === 1 ? "" : "s"} must be fixed first; submitting will list {issueCount === 1 ? "it" : "them"}.
          </p>
        )}
      </ConfirmAction>,
    );
  }
  if ((status === "IN_REVIEW" || status === "APPROVED") && capabilities.canReview && actions.requestChanges) {
    buttons.push(
      <ConfirmAction
        key="changes"
        action={actions.requestChanges}
        fields={fields}
        triggerLabel="Request changes"
        triggerIcon={<Undo2 aria-hidden="true" />}
        title="Send back to draft?"
        description="The author sees your notes. The item returns to Draft and any approval is cleared."
        confirmLabel="Request changes"
        reason={{ name: "notes", label: "What needs to change?", required: true, maxLength: 2000 }}
        successMessage="Sent back to draft."
      />,
    );
  }
  if (status === "IN_REVIEW" && capabilities.canReview && actions.approve) {
    buttons.push(
      <ConfirmAction
        key="approve"
        action={actions.approve}
        fields={fields}
        triggerLabel="Approve"
        triggerVariant="secondary"
        triggerIcon={<CheckCheck aria-hidden="true" />}
        disabled={approveBlocked}
        disabledReason="You authored this version. Another reviewer must approve it (four-eyes rule)."
        title={aiGenerated ? "Approve AI-generated content?" : "Approve?"}
        description={
          aiGenerated
            ? "This draft was generated by AI. Approve only after checking every fact, answer, step and mark scheme yourself, and that it does not reproduce copyrighted text."
            : `Confirm you have reviewed ${itemLabel}: accuracy, notation, curriculum alignment, copyright status and source.`
        }
        confirmLabel="Approve"
        reason={
          aiGenerated
            ? { name: "notes", label: "What did you check?", required: true, maxLength: 2000, hint: "Required for AI-generated content: answers re-derived, facts and notation checked, originality." }
            : { name: "notes", label: "Review notes", maxLength: 2000 }
        }
        successMessage="Approved."
      />,
    );
  }
  if (status === "APPROVED" && capabilities.canPublish && actions.publish) {
    buttons.push(
      <ConfirmAction
        key="publish"
        action={actions.publish}
        fields={fields}
        triggerLabel={draftOfId ? "Publish changes" : "Publish"}
        triggerVariant="primary"
        triggerIcon={<Upload aria-hidden="true" />}
        title="Publish to students?"
        description={
          draftOfId
            ? `Students will see the new version of ${itemLabel} immediately. The previous version stays in the revision history.`
            : `Students will see ${itemLabel} immediately. Published content can't be edited in place: later edits go through a new draft.`
        }
        confirmLabel="Publish"
        reason={{ name: "changeNote", label: "Change note", maxLength: 2000, hint: "Shown in the revision history." }}
        successMessage="Published."
      />,
    );
  }
  if (status === "PUBLISHED" && draftOfId === null && capabilities.canDraft && actions.startEdit && !pendingDraftId) {
    buttons.push(
      <ConfirmAction
        key="edit"
        action={actions.startEdit}
        fields={fields}
        triggerLabel="Edit published version"
        triggerVariant="secondary"
        triggerIcon={<PenLine aria-hidden="true" />}
        title="Start a new draft?"
        description={`A draft copy of ${itemLabel} is created for editing. Students keep seeing the published version until the draft is approved and published.`}
        confirmLabel="Create draft copy"
        successMessage="Draft copy created."
      />,
    );
  }
  if (status === "PUBLISHED" && draftOfId === null && capabilities.canArchive && actions.archive) {
    buttons.push(
      <ConfirmAction
        key="archive"
        action={actions.archive}
        fields={fields}
        triggerLabel="Archive"
        triggerIcon={<Archive aria-hidden="true" />}
        tone="danger"
        disabled={Boolean(pendingDraftId)}
        disabledReason="Publish or discard the pending draft copy before archiving."
        title="Archive?"
        description={`Students will no longer see ${itemLabel}. Past attempts and the revision history are kept.`}
        confirmLabel="Archive"
        successMessage="Archived."
      />,
    );
  }
  if (status === "ARCHIVED" && draftOfId === null && capabilities.canArchive && actions.reopen) {
    buttons.push(
      <ConfirmAction
        key="reopen"
        action={actions.reopen}
        fields={fields}
        triggerLabel="Restore to draft"
        triggerIcon={<ArchiveRestore aria-hidden="true" />}
        title="Restore to draft?"
        description={`${capitalise(itemLabel)} becomes an editable draft (a new revision). Students see it again only after it is reviewed and published.`}
        confirmLabel="Restore to draft"
        successMessage="Restored to draft."
      />,
    );
  }
  if (draftOfId !== null && status !== "PUBLISHED" && capabilities.canDraft && actions.discard) {
    buttons.push(
      <ConfirmAction
        key="discard"
        action={actions.discard}
        fields={fields}
        triggerLabel="Discard draft copy"
        triggerIcon={<Trash2 aria-hidden="true" />}
        tone="danger"
        title="Discard this draft copy?"
        description="The edits in this copy are deleted. The published version is not affected."
        confirmLabel="Discard"
        successMessage="Draft copy discarded."
      />,
    );
  }

  if (buttons.length === 0) return null;
  return (
    <div className={className}>
      <div className="flex flex-wrap gap-2">{buttons}</div>
      {approveBlocked && status === "IN_REVIEW" && capabilities.canReview && actions.approve && (
        <p className="mt-2 text-sm text-muted">You authored this version, so another reviewer must approve it (four-eyes rule).</p>
      )}
    </div>
  );
}
