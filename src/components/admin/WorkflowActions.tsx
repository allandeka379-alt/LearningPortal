import { Archive, ArchiveRestore, CheckCheck, Send, Undo2, Upload } from "lucide-react";
import type { ReactNode } from "react";
import { ConfirmAction } from "./ConfirmAction";
import type { AdminFormAction } from "./form-state";

/**
 * The content workflow buttons (§41, §42; CLAUDE.md "Database rules"): DRAFT → IN_REVIEW → APPROVED → PUBLISHED →
 * ARCHIVED, plus "request changes" back to DRAFT and "restore to draft" (ARCHIVED → DRAFT, a new revision). Shows only the transitions that are legal from `status` AND that
 * the caller says the actor may perform; every step goes through a confirmation dialog because publishing and
 * archiving are visible to students and audited.
 *
 * The Server Actions passed here must call the shared publish helper (`src/server/content/publish.ts`) — this
 * component only renders. Four-eyes: when the actor authored the item and four-eyes is on, "Approve" is disabled with
 * the reason; AI-generated drafts always need a human approver.
 *
 * Server-compatible wrapper around client `ConfirmAction`s.
 */

export type WorkflowStatus = "DRAFT" | "IN_REVIEW" | "APPROVED" | "PUBLISHED" | "ARCHIVED";

export interface WorkflowActionHandlers {
  submit?: AdminFormAction<unknown>;
  requestChanges?: AdminFormAction<unknown>;
  approve?: AdminFormAction<unknown>;
  publish?: AdminFormAction<unknown>;
  archive?: AdminFormAction<unknown>;
  /** ARCHIVED → DRAFT ("Restore to draft"; `content.archive`). */
  reopen?: AdminFormAction<unknown>;
}

export interface WorkflowActionsProps {
  status: WorkflowStatus;
  /** Hidden fields for every action (e.g. `{ id, entityType }`). */
  fields: Readonly<Record<string, string>>;
  /** Server Actions; omit the ones the actor may not perform (each action still re-checks permission). */
  actions: WorkflowActionHandlers;
  /** The actor is the item's author (four-eyes: may not approve their own work when enabled). */
  isOwnWork?: boolean;
  /** Whether the four-eyes rule is enforced (database `app.four_eyes`; on in production). */
  fourEyes?: boolean;
  /** The item is AI-generated (§41): shown in the approve dialog. */
  aiGenerated?: boolean;
  /** Short item label for dialog copy, e.g. "this question". */
  itemLabel?: string;
  /** Extra content above the buttons (e.g. validation issues blocking submission). */
  notice?: ReactNode;
  className?: string;
}

function capitalise(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

export function WorkflowActions({
  status,
  fields,
  actions,
  isOwnWork = false,
  fourEyes = true,
  aiGenerated = false,
  itemLabel = "this item",
  notice,
  className,
}: WorkflowActionsProps) {
  const approveBlocked = fourEyes && isOwnWork;
  const buttons: ReactNode[] = [];

  if (status === "DRAFT" && actions.submit) {
    buttons.push(
      <ConfirmAction
        key="submit"
        action={actions.submit}
        fields={fields}
        triggerLabel="Submit for review"
        triggerVariant="primary"
        triggerIcon={<Send aria-hidden="true" />}
        title="Submit for review?"
        description={`A reviewer will check ${itemLabel} before it can be published.`}
        confirmLabel="Submit for review"
        successMessage="Submitted for review."
      />,
    );
  }
  if ((status === "IN_REVIEW" || status === "APPROVED") && actions.requestChanges) {
    buttons.push(
      <ConfirmAction
        key="changes"
        action={actions.requestChanges}
        fields={fields}
        triggerLabel="Request changes"
        triggerIcon={<Undo2 aria-hidden="true" />}
        title="Send back to draft?"
        description="The author will see your notes. The item returns to Draft."
        confirmLabel="Request changes"
        reason={{ name: "notes", label: "What needs to change?", required: true, maxLength: 2000 }}
        successMessage="Sent back to draft."
      />,
    );
  }
  if (status === "IN_REVIEW" && actions.approve) {
    buttons.push(
      <ConfirmAction
        key="approve"
        action={actions.approve}
        fields={fields}
        triggerLabel="Approve"
        triggerVariant="secondary"
        triggerIcon={<CheckCheck aria-hidden="true" />}
        disabled={approveBlocked}
        disabledReason="You authored this item. Another reviewer must approve it (four-eyes rule)."
        title="Approve?"
        description={
          aiGenerated
            ? "This draft was generated by AI. Approve only after checking every fact, answer and mark scheme yourself."
            : `Confirm you have reviewed ${itemLabel}, including its copyright status and source.`
        }
        confirmLabel="Approve"
        reason={{ name: "notes", label: "Review notes", maxLength: 2000 }}
        successMessage="Approved."
      />,
    );
  }
  if (status === "APPROVED" && actions.publish) {
    buttons.push(
      <ConfirmAction
        key="publish"
        action={actions.publish}
        fields={fields}
        triggerLabel="Publish"
        triggerVariant="primary"
        triggerIcon={<Upload aria-hidden="true" />}
        title="Publish to students?"
        description={`Students will see ${itemLabel} immediately. Published content can't be edited in place: later edits go through a new draft.`}
        confirmLabel="Publish"
        successMessage="Published."
      />,
    );
  }
  if (status === "PUBLISHED" && actions.archive) {
    buttons.push(
      <ConfirmAction
        key="archive"
        action={actions.archive}
        fields={fields}
        triggerLabel="Archive"
        triggerIcon={<Archive aria-hidden="true" />}
        tone="danger"
        title="Archive?"
        description={`Students will no longer see ${itemLabel}. Past attempts and history are kept.`}
        confirmLabel="Archive"
        successMessage="Archived."
      />,
    );
  }
  if (status === "ARCHIVED" && actions.reopen) {
    buttons.push(
      <ConfirmAction
        key="reopen"
        action={actions.reopen}
        fields={fields}
        triggerLabel="Restore to draft"
        triggerIcon={<ArchiveRestore aria-hidden="true" />}
        title="Restore to draft?"
        description={`${capitalise(itemLabel)} becomes an editable draft (a new revision). Students see it again only after it is reviewed and published.`}
        confirmLabel="Restore to draft"
        successMessage="Restored to draft."
      />,
    );
  }

  if (buttons.length === 0 && !notice) return null;
  return (
    <div className={className}>
      {notice}
      {buttons.length > 0 && <div className="flex flex-wrap gap-2">{buttons}</div>}
      {approveBlocked && status === "IN_REVIEW" && actions.approve && (
        <p className="mt-2 text-sm text-muted">You authored this item, so another reviewer must approve it (four-eyes rule).</p>
      )}
    </div>
  );
}
